def _inside(path: Path, parent: Path) -> bool:
    try:
        path.relative_to(parent)
        return True
    except ValueError:
        return False


def _load_codex_discovery(
    discovery: Path,
    allowed_paths: set[Path],
    setup_root: Path,
    legacy_files: dict[Path, str],
) -> tuple[set[str], dict[str, str]]:
    """Accept only exact, provenance-backed Codex project artifacts."""
    if discovery.is_symlink():
        raise ValueError(f"managed Codex discovery file must not be a symlink: {discovery}")
    if not discovery.exists():
        return set(), {}
    if not discovery.is_file():
        raise ValueError(f"managed Codex discovery path is not a file: {discovery}")
    data = json.loads(discovery.read_text(encoding="utf-8"))
    if not isinstance(data, dict) or data.get("schema_version") not in {1, 2} or data.get("host") != "codex":
        raise ValueError(f"unsupported LawyeredOS Codex discovery schema: {discovery}")
    package_digest_value = data.get("package_digest")
    if not isinstance(package_digest_value, str) or len(package_digest_value) != 64 or any(
        character not in "0123456789abcdef" for character in package_digest_value
    ):
        raise ValueError(f"invalid package digest in Codex discovery: {discovery}")
    raw_paths = data.get("managed_paths")
    if not isinstance(raw_paths, list) or not all(isinstance(item, str) for item in raw_paths):
        raise ValueError(f"invalid managed_paths in Codex discovery: {discovery}")
    if len(raw_paths) != len(set(raw_paths)):
        raise ValueError(f"duplicate managed_paths in Codex discovery: {discovery}")
    allowed = {str(path.absolute()) for path in allowed_paths}
    managed: set[str] = set()
    for raw in raw_paths:
        candidate = Path(raw)
        if not candidate.is_absolute() or str(candidate.absolute()) != raw or raw not in allowed:
            raise ValueError(f"discovery path is outside the LawyeredOS Codex namespace: {raw}")
        managed.add(raw)
    raw_fingerprints = data.get("managed_fingerprints", {})
    if not isinstance(raw_fingerprints, dict) or not all(
        isinstance(key, str) and isinstance(value, str) and len(value) == 64
        and all(character in "0123456789abcdef" for character in value)
        for key, value in raw_fingerprints.items()
    ):
        raise ValueError(f"invalid managed_fingerprints in Codex discovery: {discovery}")
    if not set(raw_fingerprints).issubset(managed):
        raise ValueError(f"Codex discovery fingerprints include an unmanaged path: {discovery}")
    fingerprints = dict(raw_fingerprints)
    plugin_root = setup_root / "plugins"
    for raw in managed:
        path = Path(raw)
        if not path.exists() and not path.is_symlink():
            continue
        expected = fingerprints.get(raw)
        if expected is None:
            # Schema-v1 compatibility is deliberately narrow: links must resolve
            # into a marked versioned core, while wrappers must match generated bytes.
            if path.is_symlink():
                target = path.resolve(strict=True)
                if not _inside(target, plugin_root.resolve()):
                    raise ValueError(f"legacy managed Codex link escapes the plugin namespace: {path}")
                plugin = next((parent for parent in (target, *target.parents) if parent.parent == plugin_root), None)
                marker = plugin / ".lawyeredos-package.json" if plugin else None
                if marker is None or not marker.is_file():
                    raise ValueError(f"legacy managed Codex link has no package marker: {path}")
                marker_data = json.loads(marker.read_text(encoding="utf-8"))
                if marker_data.get("digest") != package_digest_value or marker_data.get("host") != "codex":
                    raise ValueError(f"legacy managed Codex link has untrusted package provenance: {path}")
            elif path in legacy_files and path.is_file() and path.read_text(encoding="utf-8") == legacy_files[path]:
                pass
            else:
                raise ValueError(f"managed Codex discovery path has no trusted fingerprint: {path}")
            expected = managed_fingerprint(path)
            fingerprints[raw] = expected
        if managed_fingerprint(path) != expected:
            raise ValueError(f"managed Codex discovery path fingerprint changed: {path}")
    return managed, fingerprints


def dependency_report(modules: tuple[str, ...]) -> list[dict[str, str | bool]]:
    selected = set(modules)
    checks: list[dict[str, str | bool]] = [{
        "name": "Python 3.11+",
        "required": True,
        "available": sys.version_info >= (3, 11),
        "detail": platform.python_version(),
        "fix": "Install Python 3.11 or newer, then rerun this wizard.",
    }]
    for module, label, fix, required in (
        ("openpyxl", "openpyxl", "Install openpyxl to enable optional XLSX projection.", False),
        ("docx", "python-docx", "Install requirements-documents.txt for letters or redlines.", bool(selected & {"letters", "redline"})),
        ("lxml", "lxml", "Install requirements-documents.txt for redlines.", "redline" in selected),
        ("fpdf", "fpdf2", "Install requirements-documents.txt for redlines.", "redline" in selected),
    ):
        import importlib.util
        checks.append({
            "name": label,
            "required": required,
            "available": importlib.util.find_spec(module) is not None,
            "detail": "Python module",
            "fix": fix,
        })
    codex_cli = shutil.which("codex")
    desktop = next((path for path in (
        Path("/Applications/ChatGPT.app"),
        Path.home() / "Applications" / "ChatGPT.app",
    ) if path.is_dir()), None)
    checks.append({
        "name": "Codex host",
        "required": True,
        "available": bool(codex_cli or desktop),
        "detail": codex_cli or (str(desktop) if desktop else "Codex CLI or ChatGPT desktop app not found"),
        "fix": "Install Codex CLI or the ChatGPT desktop app and sign in normally.",
    })
    for commands, label, fix in (
        (("libreoffice", "soffice"), "LibreOffice", "Install LibreOffice for visual DOCX rendering."),
        (("pdftoppm",), "Poppler", "Install Poppler for PDF page images."),
        (("ocrmypdf",), "OCRmyPDF", "Install OCRmyPDF only if OCR is needed."),
    ):
        found = next((shutil.which(command) for command in commands if shutil.which(command)), None)
        checks.append({"name": label, "required": False, "available": found is not None,
                       "detail": found or "command not found", "fix": fix})
    return checks


def normalize_answers(
    workspace: Path,
    branding_mode: str,
    branding_label: str,
    jurisdiction: str,
    modules_raw: str,
    mail: str,
    calendar: str,
    calendar_id: str,
    existing: str,
) -> Answers:
    modules = tuple(dict.fromkeys(item.strip() for item in modules_raw.split(",") if item.strip()))
    return Answers(
        workspace=workspace.expanduser().resolve(),
        branding_mode=branding_mode.strip().lower(),
        branding_label=branding_label.strip(),
        jurisdiction=jurisdiction.strip().lower(),
        modules=modules,
        mail_adapter={
            "session-tools": "codex-session-tools",
            "skip": "unavailable",
            "gmail-readonly": "gmail-api-readonly",
            "gmail-imap": "gmail-imap-readonly",
        }.get(mail, mail),
        calendar_adapter={"off": "unavailable", "google-calendar": "google-calendar-api"}.get(calendar, calendar),
        calendar_id=calendar_id.strip(),
        existing_config=existing.strip().lower(),
    )


def _projectize_skill(source: Path, destination: Path, project_name: str) -> None:
    shutil.copytree(source, destination)
    skill_path = destination / "SKILL.md"
    text = skill_path.read_text(encoding="utf-8")
    old_name = project_name.replace("lawyeredos-", "practice-", 1)
    text = text.replace(f"name: {old_name}", f"name: {project_name}", 1)
    if project_name == "lawyeredos-work-on-matter":
        text = text.replace(
            "Require the `LAWYEREDOS_CONFIG` environment variable.",
            "Require the project-local `.lawyeredos/config.toml` file; do not require or modify a global environment variable.",
        ).replace(
            "When `claude-gmail-connector` is configured, use Claude's Gmail connector only",
            "When `codex-session-tools` is configured, first inspect the tools actually exposed in this Codex session. Use a supported mail read/search tool only",
        )
        start = text.index("- When `codex-session-tools` is configured")
        end = text.index("- When `gmail-api-readonly` is configured", start)
        text = text[:start] + (
            "- When `codex-session-tools` is configured, inspect the tools actually exposed in "
            "the active session. Use only a supported, authorized mail read/search tool. A "
            "configured value is not proof that a tool is present or connected. Treat a missing "
            "tool, authorization prompt, or failed read as unavailable; only a successful bounded "
            "read establishes coverage for that request. Never draft, send, reply, forward, label, "
            "archive, or delete mail from this workflow.\n"
        ) + text[end:]
    if project_name == "lawyeredos-adversarial-panel":
        text = text.replace("through four read-only Claude lenses", "through four independent Codex lenses")
        text = text.replace("`lawyeredos:legal-review-lens` agent", "independent Codex reviewer delegation")
        text = text.replace("`lawyeredos-legal-review-lens` agent", "independent Codex reviewer delegation")
        text = text.replace("lawyeredos:legal-review-lens", "independent-codex-reviewer")
        text = text.replace("review_bundle create ", "review_bundle create --host codex ", 1)
        text = text.replace("review_orchestrator prepare ", "review_orchestrator prepare --host codex ", 1)
        text = text.replace("four independent independent Codex reviewer delegations", "four independent Codex reviewers")
        text = text.replace(
            "Reviewers\nhave only read/search tools, cannot write, browse, call connectors, run shell,\nor spawn agents.",
            "Instruct reviewers to use only bounded read/search access and not to write, browse, "
            "call connectors, execute commands, or spawn agents. Treat these as behavioral "
            "constraints and verify the source and deliverable hashes after every review.",
        )
        boundary = (
            "\n## Codex reviewer boundary\n\n"
            "A full panel requires the active Codex host to expose independent agent delegation. "
            "Give each reviewer exactly one generated task and instruct it to remain read-only. "
            "A repository skill cannot technically reduce a delegated reviewer's tools, so hash "
            "verification is mandatory. If delegation is unavailable, report the full panel as "
            "unavailable; a single-thread review is not equivalent.\n"
        )
        text = text.replace("\n## Review\n", boundary + "\n## Review\n")
    skill_path.write_text(text, encoding="utf-8")
    replacements = {
        "lawyeredos:practice-work-on-matter": "lawyeredos-work-on-matter",
        "lawyeredos:practice-matter-tracker": "lawyeredos-matter-tracker",
        "lawyeredos:practice-letterhead": "lawyeredos-letterhead",
        "lawyeredos:practice-contract-redline": "lawyeredos-contract-redline",
        "lawyeredos:practice-calendar-sync": "lawyeredos-calendar-sync",
        "lawyeredos:practice-adversarial-panel": "lawyeredos-adversarial-panel",
        "${LAWYEREDOS_ROOT}": f".lawyeredos/{CURRENT_LINK}",
        "$LAWYEREDOS_ROOT": f".lawyeredos/{CURRENT_LINK}",
        "${LAWYEREDOS_PYTHON:-python3}": f".lawyeredos/{RUNNER_FILE}",
        "$LAWYEREDOS_CONFIG": ".lawyeredos/config.toml",
        "`LAWYEREDOS_CONFIG`": "`.lawyeredos/config.toml`",
        "LAWYEREDOS_ROOT": f".lawyeredos/{CURRENT_LINK}",
        "LAWYEREDOS_PYTHON": f".lawyeredos/{RUNNER_FILE}",
        "LAWYEREDOS_CONFIG": ".lawyeredos/config.toml",
        "Claude-only": "Codex-only",
        "Claude-Only": "Codex-Only",
        "Claude reviewers": "Codex reviewers",
        "Claude Code": "Codex",
    }
    for path in sorted(destination.rglob("*")):
        if not path.is_file():
            continue
        try:
            transformed = path.read_text(encoding="utf-8")
        except UnicodeDecodeError:
            continue
        for old, new in replacements.items():
            transformed = transformed.replace(old, new)
        path.write_text(transformed, encoding="utf-8")


def _prepare_payload(plugin: Path, modules: set[str]) -> None:
    root = plugin / ".lawyeredos-codex-project" / "skills"
    root.mkdir(parents=True, exist_ok=True)
    for module in modules:
        _projectize_skill(plugin / "skills" / MODULE_SKILLS[module], root / PROJECT_SKILLS[module], PROJECT_SKILLS[module])


def expected_codex_plugin_fingerprint(source: Path, modules: tuple[str, ...], digest: str) -> str:
    with tempfile.TemporaryDirectory() as temporary:
        plugin = Path(temporary) / "plugin"
        shutil.copytree(source, plugin, ignore=_ignored)
        selected = set(modules)
        for module, skill in MODULE_SKILLS.items():
            if module not in selected:
                shutil.rmtree(plugin / "skills" / skill)
        write_template_manifest(plugin)
        _prepare_payload(plugin, selected)
        (plugin / ".lawyeredos-package.json").write_text(json.dumps({
            "version": VERSION, "digest": digest, "modules": list(modules), "host": "codex",
        }, indent=2) + "\n", encoding="utf-8")
        return managed_fingerprint(plugin)


def render_runner(plan: dict) -> str:
    python = shlex.quote(plan["runtime_python"])
    return "\n".join([
        "#!/bin/sh", "set -eu",
        f"runtime={python}",
        'base=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)',
        f'core="$base/{CURRENT_LINK}/src"',
        'if [ ! -x "$runtime" ]; then',
        '  echo "LawyeredOS runtime is unavailable; rerun setup from the retained candidate." >&2',
        "  exit 1", "fi",
        'if [ -n "${PYTHONPATH:-}" ]; then',
        '  export PYTHONPATH="$core:$PYTHONPATH"',
        "else", '  export PYTHONPATH="$core"', "fi",
        'exec "$runtime" "$@"', "",
    ])


def render_launcher(plan: dict) -> str:
    return "\n".join([
        "#!/bin/sh", "set -eu",
        f"cd {shlex.quote(plan['workspace'])}",
        'if ! command -v codex >/dev/null 2>&1; then',
        '  echo "Codex CLI is unavailable. Open this workspace in the ChatGPT desktop app instead." >&2',
        "  exit 1", "fi", "exec codex", "",
    ])


def build_plan(answers: Answers, require_new_workspace: bool = False) -> dict:
    source = package_root()
    validate_answers(answers, source)
    workspace = answers.workspace.expanduser().resolve()
    if workspace == source or _inside(workspace, source):
        raise ValueError("workspace must be outside the extracted LawyeredOS package")
    if require_new_workspace and workspace.exists() and any(workspace.iterdir()):
        raise ValueError(f"trial workspace must be new or empty: {workspace}")
    setup_root = workspace / ".lawyeredos"
    config = setup_root / "config.toml"
    managed_directories = (
        workspace, setup_root, setup_root / "scratch", setup_root / "data",
        setup_root / "plugins", workspace / ".agents", workspace / ".agents" / "skills",
    )
    for path in managed_directories:
        if path.is_symlink():
            raise ValueError(f"managed Codex directory must not be a symlink: {path}")
        if path.exists() and not path.is_dir():
            raise ValueError(f"managed Codex directory path is not a directory: {path}")
    if config.is_symlink():
        raise ValueError(f"managed config must not be a symlink: {config}")
    effective = answers
    reused = False
    if config.exists():
        if answers.existing_config == "error":
            raise ValueError(f"configuration already exists: {config}")
        if answers.existing_config == "reuse":
            loaded = load_config(config)
            if loaded.tracker_database.exists() or loaded.tracker_database.is_symlink():
                assert_private_file(loaded.tracker_database)
            if loaded.workspace_root != workspace:
                raise ValueError("existing configuration belongs to a different workspace")
            effective = Answers(
                workspace=workspace, branding_mode=loaded.branding_mode,
                branding_label=loaded.branding_label, jurisdiction=loaded.jurisdiction_profile,
                modules=tuple(name for name in MODULES if loaded.modules[name]),
                mail_adapter=loaded.mail_adapter, calendar_adapter=loaded.calendar_adapter,
                calendar_id=loaded.calendar_id, existing_config="reuse",
            )
            reused = True
        elif answers.existing_config == "replace":
            raise ValueError(
                "the Codex candidate does not replace an existing config; use reuse or a new workspace"
            )
    elif (setup_root / "data" / "matters.sqlite3").exists():
        raise ValueError("unmanaged tracker data exists without a LawyeredOS config; refusing to overwrite")
    tracker = setup_root / "data" / "matters.sqlite3"
    if tracker.exists() or tracker.is_symlink():
        assert_private_file(tracker)
    digest = package_digest(source)
    selection = hashlib.sha256(",".join(effective.modules).encode()).hexdigest()
    plugin = setup_root / "plugins" / f"lawyeredos-{VERSION}-{digest[:8]}-{selection[:6]}-codex"
    plugin_fingerprint = expected_codex_plugin_fingerprint(source, effective.modules, digest)
    if plugin.exists() and managed_fingerprint(plugin) != plugin_fingerprint:
        raise ValueError(f"installed versioned Codex core content changed: {plugin}")
    agents_root = workspace / ".agents" / "skills"
    discovery = setup_root / DISCOVERY_FILE
    rollback_state = setup_root / UPGRADE_ROLLBACK_FILE
    project_skills = {module: agents_root / PROJECT_SKILLS[module] for module in effective.modules}
    current = setup_root / CURRENT_LINK
    runner = setup_root / RUNNER_FILE
    launcher = setup_root / "launch-lawyeredos-codex.sh"
    runtime = Path(os.path.abspath(sys.executable)).expanduser()
    all_managed_paths = {
        *(agents_root / name for name in PROJECT_SKILLS.values()),
        current, runner, launcher,
    }
    prior_managed, prior_fingerprints = _load_codex_discovery(
        discovery,
        all_managed_paths,
        setup_root,
        {
            runner: render_runner({"runtime_python": str(runtime)}),
            launcher: render_launcher({"workspace": str(workspace)}),
        },
    )
    prior_plugins: set[Path] = set()
    for raw in prior_managed:
        path = Path(raw)
        if not path.is_symlink():
            continue
        target = path.resolve(strict=True)
        prior_plugin = next(
            (parent for parent in (target, *target.parents)
             if parent.parent == setup_root / "plugins"),
            None,
        )
        if prior_plugin is None:
            raise ValueError(f"managed Codex link has no versioned core: {path}")
        prior_plugins.add(prior_plugin)
    prior_plugin_fingerprints = {
        str(prior_plugin): managed_fingerprint(prior_plugin)
        for prior_plugin in sorted(prior_plugins)
    }
    if rollback_state.is_symlink():
        raise ValueError(f"managed Codex upgrade rollback state must not be a symlink: {rollback_state}")
    if rollback_state.exists():
        if not rollback_state.is_file():
            raise ValueError(f"managed Codex upgrade rollback state is not a file: {rollback_state}")
        assert_private_file(rollback_state)
        if not prior_managed:
            raise ValueError(f"Codex upgrade rollback path exists without a managed install: {rollback_state}")
        rollback_data = json.loads(rollback_state.read_text(encoding="utf-8"))
        if (
            not isinstance(rollback_data, dict)
            or rollback_data.get("schema_version") != 1
            or rollback_data.get("workspace") != str(workspace)
            or rollback_data.get("setup_root") != str(setup_root)
            or not isinstance(rollback_data.get("applied_managed_fingerprints"), dict)
        ):
            raise ValueError(f"invalid managed Codex upgrade rollback state: {rollback_state}")
    managed_candidates = {*map(str, project_skills.values()), str(current), str(runner), str(launcher)}
    for raw in managed_candidates:
        path = Path(raw)
        if (path.exists() or path.is_symlink()) and raw not in prior_managed:
            raise ValueError(f"Codex discovery/runtime target exists but is not managed by LawyeredOS: {path}")
    config_preview = None if reused else render_config(effective, plugin)
    operations = []
    for path in (workspace, setup_root, setup_root / "scratch", setup_root / "data", setup_root / "plugins", agents_root):
        if not path.exists():
            operations.append({"action": "create_directory", "path": str(path)})
    if not plugin.exists():
        operations.append({"action": "install_versioned_core", "path": str(plugin)})
    operations.append({"action": "reuse" if reused else "create_or_replace_config", "path": str(config)})
    for path in project_skills.values():
        operations.append({"action": "install_codex_project_skill", "path": str(path)})
    operations.extend([
        {"action": "link_current_codex_core", "path": str(current)},
        {"action": "write_runtime_wrapper", "path": str(runner)},
        {"action": "write_codex_launcher", "path": str(launcher)},
    ])
    return {
        "schema_version": 1, "host": "codex", "require_new_workspace": require_new_workspace,
        "source": str(source), "workspace": str(workspace), "setup_root": str(setup_root),
        "config": str(config), "plugin": str(plugin), "current": str(current),
        "runner": str(runner), "launcher": str(launcher), "discovery": str(discovery),
        "upgrade_rollback_state": str(rollback_state),
        "runtime_python": str(runtime), "package_digest": digest, "selection_digest": selection,
        "plugin_fingerprint": plugin_fingerprint,
        "project_skills": {module: str(path) for module, path in project_skills.items()},
        "prior_managed": sorted(prior_managed),
        "prior_fingerprints": prior_fingerprints,
        "prior_plugin_fingerprints": prior_plugin_fingerprints,
        "preflight_paths": {
            str(path): path_snapshot(path)
            for path in (
                config, setup_root / "data" / "matters.sqlite3", runner, launcher,
                discovery,
                rollback_state,
            )
        },
        "answers": {**asdict(effective), "workspace": str(workspace), "modules": list(effective.modules)},
        "dependencies": dependency_report(effective.modules), "config_preview": config_preview,
        "operations": operations,
        "notes": [
            "No user-global ~/.codex or ~/.agents files will be changed.",
            "No project .codex/config.toml file will be created or changed.",
            "Existing unrelated project skills are preserved; name collisions fail closed.",
            "Session mail tools are configured, not assumed connected; only a successful bounded read proves availability."
            if effective.mail_adapter == "codex-session-tools" else
            "Email was explicitly skipped; email-dependent workflows will disclose that email was not checked."
            if effective.mail_adapter == "unavailable" else
            "The experimental portable Gmail IMAP adapter requires user-provisioned credentials through the named environment variables or an explicitly configured macOS Keychain service; setup never retrieves or stores them."
            if effective.mail_adapter == "gmail-imap-readonly" else
            "The experimental local Gmail REST adapter requires a separately provisioned gmail.readonly token in the named environment variable; setup never retrieves or stores it.",
        ],
    }


def apply_plan(plan: dict) -> dict:
    missing = [item["name"] for item in plan["dependencies"] if item["required"] and not item["available"]]
    if missing:
        raise ValueError(f"required dependencies missing: {', '.join(missing)}")
    workspace = Path(plan["workspace"])
    validate_workspace_isolation(workspace)
    if plan.get("require_new_workspace") and workspace.exists() and any(workspace.iterdir()):
        raise ValueError(f"trial workspace is no longer empty: {workspace}")
    source, setup_root, plugin = Path(plan["source"]), Path(plan["setup_root"]), Path(plan["plugin"])
    config, current = Path(plan["config"]), Path(plan["current"])
    tracker = setup_root / "data" / "matters.sqlite3"
    runner, launcher, discovery = Path(plan["runner"]), Path(plan["launcher"]), Path(plan["discovery"])
    rollback_state = Path(plan["upgrade_rollback_state"])
    managed_directories = (
        workspace, setup_root, setup_root / "scratch", setup_root / "data",
        setup_root / "plugins", workspace / ".agents", workspace / ".agents" / "skills",
        plugin,
    )
    _validate_managed_paths(managed_directories, (config, runner, launcher, discovery, rollback_state))
    assert_preflight_paths(plan.get("preflight_paths", {}))
    for directory in (setup_root, setup_root / "scratch", setup_root / "data", setup_root / "plugins"):
        if directory.exists() or directory.is_symlink():
            assert_private_directory(directory)
    for private_file in (config, tracker, discovery, rollback_state):
        if private_file.exists() or private_file.is_symlink():
            assert_private_file(private_file)
    allowed_managed = {
        *(workspace / ".agents" / "skills" / name for name in PROJECT_SKILLS.values()),
        current, runner, launcher,
    }
    current_managed, current_fingerprints = _load_codex_discovery(
        discovery,
        allowed_managed,
        setup_root,
        {runner: render_runner(plan), launcher: render_launcher(plan)},
    )
    if current_managed != set(plan.get("prior_managed", [])) or current_fingerprints != plan.get("prior_fingerprints", {}):
        raise ValueError("LawyeredOS Codex discovery state changed after preview; build a new plan")
    approved_prior_plugins = plan.get("prior_plugin_fingerprints", {})
    if not isinstance(approved_prior_plugins, dict):
        raise ValueError("approved prior Codex core fingerprints are invalid")
    for raw, expected in approved_prior_plugins.items():
        prior_plugin = Path(raw)
        if (
            not prior_plugin.is_absolute()
            or prior_plugin.parent != setup_root / "plugins"
            or not isinstance(expected, str)
            or len(expected) != 64
            or managed_fingerprint(prior_plugin) != expected
        ):
            raise ValueError("retained prior Codex core changed after preview; build a new plan")
    for path in {*(Path(raw) for raw in plan["project_skills"].values()), current}:
        if (path.exists() or path.is_symlink()) and str(path) not in current_managed:
            raise ValueError(f"Codex discovery target appeared after preview and is not managed: {path}")
    created: list[Path] = []
    replaced_links: list[tuple[Path, str]] = []
    replaced_files: list[tuple[Path, bytes, int]] = []
    changed: list[str] = []
    prior_discovery_text = discovery.read_text(encoding="utf-8") if discovery.is_file() else None
    prior_link_targets = {
        str(path): os.readlink(path)
        for path in {*(Path(raw) for raw in plan["project_skills"].values()), current}
        if path.is_symlink()
    }
    try:
        if plugin.exists() and managed_fingerprint(plugin) != plan["plugin_fingerprint"]:
            raise ValueError(f"installed versioned Codex core content changed after preview: {plugin}")
        for path in (
            workspace, setup_root, setup_root / "scratch", setup_root / "data",
            setup_root / "plugins", workspace / ".agents", workspace / ".agents" / "skills",
        ):
            if not path.exists():
                if path == workspace or path == workspace / ".agents" or path == workspace / ".agents" / "skills":
                    path.mkdir(parents=True, exist_ok=False)
                else:
                    ensure_private_directory(path)
                created.append(path)
            elif path == setup_root or setup_root in path.parents:
                assert_private_directory(path)
        if not plugin.exists():
            created.append(plugin)
            shutil.copytree(source, plugin, ignore=_ignored)
            selected = set(plan["answers"]["modules"])
            for module, skill in MODULE_SKILLS.items():
                if module not in selected:
                    shutil.rmtree(plugin / "skills" / skill)
            write_template_manifest(plugin)
            _prepare_payload(plugin, selected)
            (plugin / ".lawyeredos-package.json").write_text(json.dumps({
                "version": VERSION, "digest": plan["package_digest"], "modules": plan["answers"]["modules"],
                "host": "codex",
            }, indent=2) + "\n", encoding="utf-8")
            if managed_fingerprint(plugin) != plan["plugin_fingerprint"]:
                raise ValueError(f"installed Codex core does not match the approved build: {plugin}")
            changed.append(str(plugin))
        marker = plugin / ".lawyeredos-package.json"
        if not marker.is_file() or json.loads(marker.read_text(encoding="utf-8")).get("digest") != plan["package_digest"]:
            raise ValueError(f"installed core does not match this candidate: {plugin}")
        desired = {Path(path) for path in plan["project_skills"].values()}
        desired.update({current, runner, launcher})
        prior_managed = set(plan.get("prior_managed", []))
        stale = [Path(raw) for raw in prior_managed if Path(raw) not in desired and (Path(raw).exists() or Path(raw).is_symlink())]
        if stale:
            raise ValueError(f"managed paths require a separate reviewed migration: {', '.join(map(str, stale))}")

        def install_link(target: Path, destination: Path, label: str) -> None:
            if target.is_symlink() and target.resolve() == destination.resolve():
                return
            if target.is_symlink() and str(target) in prior_managed:
                previous = os.readlink(target)
                target.unlink()
                try:
                    target.symlink_to(destination, target_is_directory=True)
                except Exception:
                    target.symlink_to(previous, target_is_directory=True)
                    raise
                replaced_links.append((target, previous))
                changed.append(str(target))
                return
            if target.exists() or target.is_symlink():
                raise ValueError(f"refusing to overwrite {label}: {target}")
            target.symlink_to(destination, target_is_directory=True)
            created.append(target)
            changed.append(str(target))

        for module, raw in plan["project_skills"].items():
            source_skill = plugin / ".lawyeredos-codex-project" / "skills" / PROJECT_SKILLS[module]
            install_link(Path(raw), source_skill, "project skill")
        install_link(current, plugin, "current core link")
        for path, content in ((runner, render_runner(plan)), (launcher, render_launcher(plan))):
            if path.exists() and path.read_text(encoding="utf-8") != content:
                raise ValueError(f"refusing to overwrite modified managed launcher: {path}")
            if not path.exists():
                created.append(path)
                path.write_text(content, encoding="utf-8")
                path.chmod(0o700)
                changed.append(str(path))
        if plan["config_preview"] is not None:
            if config.exists():
                raise ValueError("Codex candidate does not replace an existing config without a separate reviewed migration")
            created.append(config)
            create_private_file(config, plan["config_preview"].encode("utf-8"))
            initialize_tracker_exclusive(tracker)
            created.append(tracker)
            changed.extend([str(config), str(tracker)])
        managed = sorted(str(path) for path in desired)
        discovery_text = json.dumps({
            "schema_version": 2, "host": "codex", "package_digest": plan["package_digest"],
            "managed_paths": managed,
            "managed_fingerprints": {
                str(path): managed_fingerprint(path)
                for path in sorted(desired)
            },
        }, indent=2, sort_keys=True) + "\n"
        if not discovery.exists() or discovery.read_text(encoding="utf-8") != discovery_text:
            if discovery.exists():
                replaced_files.append((discovery, discovery.read_bytes(), discovery.stat().st_mode))
            else:
                created.append(discovery)
            replace_private_file(discovery, discovery_text.encode("utf-8"))
            changed.append(str(discovery))
        if prior_discovery_text is not None and replaced_links:
            if not approved_prior_plugins:
                raise ValueError("Codex upgrade has no retained prior core to fingerprint")
            rollback_record = {
                "schema_version": 1,
                "workspace": str(workspace),
                "setup_root": str(setup_root),
                "prior_discovery": json.loads(prior_discovery_text),
                "prior_managed_fingerprints": plan["prior_fingerprints"],
                "prior_link_targets": prior_link_targets,
                "prior_plugin_fingerprints": approved_prior_plugins,
                "applied_package_digest": plan["package_digest"],
                "applied_plugin": str(plugin),
                "applied_plugin_fingerprint": managed_fingerprint(plugin),
                "applied_managed_fingerprints": {
                    str(path): managed_fingerprint(path) for path in sorted(desired)
                },
            }
            if rollback_state.exists():
                replaced_files.append(
                    (rollback_state, rollback_state.read_bytes(), rollback_state.stat().st_mode)
                )
            else:
                created.append(rollback_state)
            replace_private_file(
                rollback_state,
                (json.dumps(rollback_record, indent=2, sort_keys=True) + "\n").encode("utf-8"),
            )
            changed.append(str(rollback_state))
        with sqlite3.connect(load_config(config).tracker_database) as connection:
            if connection.execute("PRAGMA quick_check").fetchone()[0] != "ok":
                raise ValueError("tracker quick_check failed")
    except BaseException as exc:
        rollback_problems: list[str] = []
        for path, content, mode in reversed(replaced_files):
            try:
                path.write_bytes(content)
                path.chmod(mode)
            except OSError as rollback_exc:
                rollback_problems.append(f"restore {path}: {rollback_exc}")
        for path, previous in reversed(replaced_links):
            try:
                path.unlink(missing_ok=True)
                path.symlink_to(previous, target_is_directory=True)
            except OSError as rollback_exc:
                rollback_problems.append(f"restore {path}: {rollback_exc}")
        for path in reversed(created):
            try:
                if path.is_symlink() or path.is_file():
                    path.unlink(missing_ok=True)
                elif path.is_dir():
                    if path == plugin:
                        shutil.rmtree(path)
                    else:
                        path.rmdir()
            except OSError as rollback_exc:
                rollback_problems.append(f"remove {path}: {rollback_exc}")
        if rollback_problems:
            raise RuntimeError(
                "setup failed and automatic rollback was incomplete: "
                + "; ".join(rollback_problems)
            ) from exc
        raise
    return {"ok": True, "idempotent": not changed, "changed": changed, "workspace": str(workspace),
            "config": str(config), "plugin": str(plugin), "launcher": str(launcher),
            "skills": plan["project_skills"], "discovery": str(discovery),
            "upgrade_rollback_state": str(rollback_state)}


def rollback_upgrade(workspace: Path) -> dict:
    """Restore the links and discovery record from the latest Codex upgrade."""
    requested = workspace.expanduser().absolute()
    if requested.is_symlink():
        raise ValueError(f"workspace must not be a symlink for rollback: {requested}")
    workspace = requested.resolve()
    setup_root = workspace / ".lawyeredos"
    skills_root = workspace / ".agents" / "skills"
    plugins_root = setup_root / "plugins"
    discovery = setup_root / DISCOVERY_FILE
    state_path = setup_root / UPGRADE_ROLLBACK_FILE
    _validate_managed_paths(
        (workspace, setup_root, plugins_root, workspace / ".agents", skills_root),
        (discovery, state_path),
    )
    assert_private_directory(setup_root)
    assert_private_directory(plugins_root)
    assert_private_file(discovery)
    assert_private_file(state_path)
    state = json.loads(state_path.read_text(encoding="utf-8"))
    if not isinstance(state, dict) or state.get("schema_version") != 1:
        raise ValueError(f"unsupported Codex upgrade rollback schema: {state_path}")
    if state.get("workspace") != str(workspace) or state.get("setup_root") != str(setup_root):
        raise ValueError("Codex upgrade rollback state belongs to a different workspace")
    prior_discovery = state.get("prior_discovery")
    if (
        not isinstance(prior_discovery, dict)
        or prior_discovery.get("schema_version") not in {1, 2}
        or prior_discovery.get("host") != "codex"
    ):
        raise ValueError("Codex upgrade rollback has invalid prior discovery state")
    allowed = {
        *(skills_root / name for name in PROJECT_SKILLS.values()),
        setup_root / CURRENT_LINK,
        setup_root / RUNNER_FILE,
        setup_root / "launch-lawyeredos-codex.sh",
    }
    current_managed, current_fingerprints = _load_codex_discovery(
        discovery,
        allowed,
        setup_root,
        {
            setup_root / RUNNER_FILE: render_runner({
                "runtime_python": str(Path(os.path.abspath(sys.executable)).expanduser())
            }),
            setup_root / "launch-lawyeredos-codex.sh": render_launcher({"workspace": str(workspace)}),
        },
    )
    applied_fingerprints = state.get("applied_managed_fingerprints")
    if not isinstance(applied_fingerprints, dict) or current_fingerprints != applied_fingerprints:
        raise ValueError("managed Codex state changed after upgrade; refusing rollback")
    if current_managed != set(applied_fingerprints):
        raise ValueError("managed Codex path set changed after upgrade; refusing rollback")
    applied_plugin = Path(state.get("applied_plugin", ""))
    if (
        not applied_plugin.is_absolute()
        or applied_plugin.parent != plugins_root
        or not applied_plugin.name.startswith("lawyeredos-")
        or not applied_plugin.is_dir()
        or applied_plugin.is_symlink()
        or managed_fingerprint(applied_plugin) != state.get("applied_plugin_fingerprint")
    ):
        raise ValueError("applied Codex core changed after upgrade; refusing rollback")
    raw_targets = state.get("prior_link_targets")
    if not isinstance(raw_targets, dict) or not raw_targets:
        raise ValueError("Codex upgrade rollback is missing prior link targets")
    expected_link_paths = {raw for raw in current_managed if Path(raw).is_symlink()}
    if set(raw_targets) != expected_link_paths:
        raise ValueError("Codex upgrade rollback link set does not match the installed upgrade")
    prior_digest = prior_discovery.get("package_digest")
    validated_targets: dict[Path, str] = {}
    validated_prior_plugins: set[Path] = set()
    for raw, target_raw in raw_targets.items():
        path = Path(raw)
        if (
            not isinstance(raw, str)
            or not path.is_absolute()
            or str(path.absolute()) != raw
            or path not in allowed
            or raw not in current_managed
            or not path.is_symlink()
            or not isinstance(target_raw, str)
        ):
            raise ValueError(f"invalid managed link in Codex upgrade rollback: {raw}")
        target = Path(target_raw)
        if not target.is_absolute() or not _inside(target, plugins_root):
            raise ValueError(f"prior Codex link target escapes the plugin namespace: {target}")
        plugin = next(
            (parent for parent in (target, *target.parents) if parent.parent == plugins_root),
            None,
        )
        marker = plugin / ".lawyeredos-package.json" if plugin else None
        if marker is None or not marker.is_file() or marker.is_symlink():
            raise ValueError(f"prior Codex link target lacks package provenance: {target}")
        marker_data = json.loads(marker.read_text(encoding="utf-8"))
        if marker_data.get("host") != "codex" or marker_data.get("digest") != prior_digest:
            raise ValueError(f"prior Codex link target has mismatched package provenance: {target}")
        if not target.exists() or target.is_symlink():
            raise ValueError(f"prior Codex link target is unavailable: {target}")
        validated_prior_plugins.add(plugin)
        validated_targets[path] = target_raw
    prior_plugin_fingerprints = state.get("prior_plugin_fingerprints")
    if (
        not isinstance(prior_plugin_fingerprints, dict)
        or set(prior_plugin_fingerprints) != {str(plugin) for plugin in validated_prior_plugins}
        or not all(isinstance(value, str) and len(value) == 64
                   for value in prior_plugin_fingerprints.values())
    ):
        raise ValueError("Codex upgrade rollback has invalid prior core fingerprints")
    for plugin in validated_prior_plugins:
        if managed_fingerprint(plugin) != prior_plugin_fingerprints[str(plugin)]:
            raise ValueError("retained prior Codex core changed after upgrade; refusing rollback")
    prior_paths = prior_discovery.get("managed_paths")
    if not isinstance(prior_paths, list) or set(prior_paths) != current_managed:
        raise ValueError("prior Codex managed path set does not match the installed upgrade")
    prior_fingerprints = state.get("prior_managed_fingerprints")
    if (
        not isinstance(prior_fingerprints, dict)
        or set(prior_fingerprints) != current_managed
        or not all(isinstance(value, str) and len(value) == 64 for value in prior_fingerprints.values())
    ):
        raise ValueError("Codex upgrade rollback has invalid prior managed fingerprints")
    for path, target in validated_targets.items():
        expected = hashlib.sha256(b"symlink\0" + target.encode()).hexdigest()
        if prior_fingerprints[str(path)] != expected:
            raise ValueError(f"prior Codex link fingerprint does not match its target: {path}")
    prior_discovery = {
        **prior_discovery,
        "schema_version": 2,
        "managed_fingerprints": prior_fingerprints,
    }

    restored: list[str] = []
    applied_targets = {path: os.readlink(path) for path in validated_targets}

    def replace_link(path: Path, target: str, suffix: str) -> None:
        staged = path.parent / f".{path.name}.lawyeredos-{suffix}-{os.getpid()}"
        if staged.exists() or staged.is_symlink():
            raise ValueError(f"rollback staging path already exists: {staged}")
        try:
            staged.symlink_to(target, target_is_directory=True)
            os.replace(staged, path)
        finally:
            staged.unlink(missing_ok=True)

    try:
        for path, target in validated_targets.items():
            replace_link(path, target, "rollback")
            restored.append(str(path))
        replace_private_file(
            discovery,
            (json.dumps(prior_discovery, indent=2, sort_keys=True) + "\n").encode("utf-8"),
        )
    except BaseException as exc:
        recovery_problems = []
        for raw in reversed(restored):
            path = Path(raw)
            try:
                replace_link(path, applied_targets[path], "rollback-recovery")
            except (OSError, ValueError) as recovery_exc:
                recovery_problems.append(f"restore {path}: {recovery_exc}")
        if recovery_problems:
            raise RuntimeError(
                "Codex upgrade rollback failed and recovery was incomplete: "
                + "; ".join(recovery_problems)
            ) from exc
        raise
    state_path.unlink()
    return {
        "ok": True,
        "status": "upgrade_rolled_back",
        "restored": sorted(restored),
        "preserved_plugin": str(applied_plugin),
        "discovery": str(discovery),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Preview and apply a project-local LawyeredOS setup for Codex")
    parser.add_argument("--workspace", required=True)
    parser.add_argument("--branding-mode", choices=("neutral", "individual", "firm"), default="neutral")
    parser.add_argument("--branding-label", default="Organization")
    parser.add_argument("--jurisdiction", choices=("none", "ontario"), default="none")
    parser.add_argument("--modules", default=",".join(MODULES))
    parser.add_argument(
        "--mail", choices=("session-tools", "skip", "gmail-readonly", "gmail-imap"),
    )
    parser.add_argument("--calendar", choices=("off", "google-calendar"), default="off")
    parser.add_argument("--calendar-id", default="")
    parser.add_argument("--existing-config", choices=("reuse", "error"), default="error")
    parser.add_argument("--require-new-workspace", action="store_true")
    parser.add_argument("--apply", action="store_true")
    parser.add_argument("--rollback-upgrade", action="store_true")
    parser.add_argument("--yes", action="store_true")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args(argv)
    try:
        if args.rollback_upgrade:
            if args.apply:
                raise ValueError("choose either --apply or --rollback-upgrade")
            if not args.yes:
                raise ValueError("rollback-upgrade requires --yes after reviewing the managed workspace")
            print(json.dumps(rollback_upgrade(Path(args.workspace)), indent=2, sort_keys=True))
            return 0
        if args.mail is None:
            raise ValueError("--mail is required for setup preview and apply")
        answers = normalize_answers(Path(args.workspace), args.branding_mode, args.branding_label,
                                    args.jurisdiction, args.modules, args.mail, args.calendar,
                                    args.calendar_id, args.existing_config)
        plan = build_plan(answers, args.require_new_workspace)
        if not args.apply:
            print(json.dumps(plan, indent=2, sort_keys=True, default=str))
            return 0
        if not args.yes:
            raise ValueError("apply requires --yes after the exact JSON preview was approved")
        print(json.dumps(apply_plan(plan), indent=2, sort_keys=True))
        return 0
    except (ValueError, OSError, json.JSONDecodeError) as exc:
        print(json.dumps({"ok": False, "error": str(exc)}, indent=2, sort_keys=True))
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
